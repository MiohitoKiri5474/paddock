//! The hidden tmux server (ADR 0001): its own socket, its own generated
//! config, and a clean environment. Every tmux process paddock starts goes
//! through [`Server::command`], so the user's own tmux server is never used.

use super::structure::{self, Structure};
use crate::paths::Paths;
use anyhow::{bail, Context, Result};
use std::path::Path;
use std::process::Command;

/// Variables passed from paddock's environment to tmux. Everything else, such
/// as `SUPACODE_*` or `TERM_PROGRAM` from the launching app, is dropped.
const KEPT_VARS: &[&str] = &[
    "HOME",
    "USER",
    "LOGNAME",
    "SHELL",
    "PATH",
    "LANG",
    "TMPDIR",
    "TMUX_TMPDIR",
    // `paddock hook` in a terminal needs paddock's own state dir and socket.
    "XDG_STATE_HOME",
    "PADDOCK_TMUX_SOCKET",
];

/// `TERM` tmux itself sees (the panes get `default-terminal`).
const SERVER_TERM: &str = "xterm-256color";
const HISTORY_LIMIT: u32 = 50_000;
/// How tmux names a window the user has not renamed.
/// Shells (not `ssh` or `mosh`) are named after their directory.
const AUTO_NAME: &str = "#{?#{m/r:^-?(ba|z|fi|da|k|tc|c)?sh$,#{pane_current_command}},\
#{b:pane_current_path},#{pane_current_command}}";

/// The environment tmux runs with: an allowlist of the given variables.
pub fn clean_env(vars: impl IntoIterator<Item = (String, String)>) -> Vec<(String, String)> {
    let mut kept: Vec<(String, String)> = vars
        .into_iter()
        .filter(|(k, _)| KEPT_VARS.contains(&k.as_str()) || k.starts_with("LC_"))
        .collect();
    kept.sort();
    kept.push(("TERM".into(), SERVER_TERM.into()));
    kept
}

/// `s` as one single-quoted shell word.
pub(crate) fn quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// paddock's own tmux config: no prefix, no status line, no key delay.
pub fn config(shell: &str) -> String {
    [
        "# Generated by paddock; rewritten on every launch.".to_string(),
        "set -s escape-time 0".into(),
        "set -s extended-keys on".into(),
        "set -g prefix None".into(),
        "set -g prefix2 None".into(),
        "set -g status off".into(),
        "set -g mouse off".into(),
        format!("set -g history-limit {HISTORY_LIMIT}"),
        "set -g default-terminal tmux-256color".into(),
        format!("set -g default-shell {}", quote(shell)),
        "set -g window-size latest".into(),
        "set -g update-environment ''".into(),
        "set-environment -g COLORTERM truecolor".into(),
        // Tabs are windows: a shell names its tab after its directory,
        // anything else after its command, until the user renames it.
        "set -g automatic-rename on".into(),
        format!("set -g automatic-rename-format {}", quote(AUTO_NAME)),
        "set -g allow-rename off".into(),
    ]
    .join("\n")
        + "\n"
}

#[derive(Clone, Debug)]
pub struct Server {
    paths: Paths,
}

impl Server {
    pub fn new(paths: Paths) -> Self {
        Self { paths }
    }

    /// A `tmux` command bound to the hidden server, with a clean environment.
    pub fn command(&self) -> Command {
        let mut c = Command::new("tmux");
        c.env_clear();
        c.envs(clean_env(std::env::vars()));
        c.arg("-L")
            .arg(&self.paths.socket)
            .arg("-f")
            .arg(self.paths.tmux_conf());
        c
    }

    pub fn run(&self, args: &[&str]) -> Result<String> {
        let out = self
            .command()
            .args(args)
            .output()
            .context("failed to run tmux")?;
        if !out.status.success() {
            bail!(
                "tmux {}: {}",
                args.join(" "),
                String::from_utf8_lossy(&out.stderr).trim()
            );
        }
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    }

    /// Write the generated config. tmux reads it when the server starts.
    pub fn write_config(&self) -> Result<()> {
        let dir = &self.paths.state_dir;
        std::fs::create_dir_all(dir)
            .with_context(|| format!("failed to create {}", dir.display()))?;
        let shell = std::env::var("SHELL")
            .ok()
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| "/bin/sh".into());
        let conf = self.paths.tmux_conf();
        std::fs::write(&conf, config(&shell))
            .with_context(|| format!("failed to write {}", conf.display()))
    }

    /// The tmux sessions on the server, oldest first; empty if no server runs.
    pub fn sessions(&self) -> Vec<Session> {
        let format = "#{session_created} #{session_id} #{session_name}";
        self.run(&["list-sessions", "-F", format])
            .map(|out| parse_sessions(&out))
            .unwrap_or_default()
    }

    /// Start a session running the user's shell, starting the server if needed.
    pub fn new_session(&self, name: &str, cwd: &Path, (cols, rows): (u16, u16)) -> Result<Session> {
        let cwd = start_dir(cwd);
        let (x, y) = (cols.to_string(), rows.to_string());
        let args = [
            "new-session",
            "-d",
            "-P",
            "-F",
            "#{session_id}",
            "-s",
            name,
            "-x",
            &x,
            "-y",
            &y,
            "-c",
            &cwd,
        ];
        let id = self.run(&args)?.trim().to_string();
        Ok(Session {
            id,
            name: name.to_string(),
        })
    }

    /// Apply the generated config to a server that already runs: tmux reads
    /// its config only when it starts, so options added since would be missing.
    pub fn apply_config(&self) -> Result<()> {
        let conf = self.paths.tmux_conf();
        self.run(&["source-file", &conf.to_string_lossy()])
            .map(drop)
    }

    /// Session `id`'s windows and panes; see [`structure`].
    pub fn structure(&self, id: &str) -> Result<Structure> {
        self.run(&["list-panes", "-s", "-t", id, "-F", structure::FORMAT])
            .map(|out| structure::parse(&out))
    }

    /// Open a new window (tab) running the user's shell in `cwd` at the end
    /// of session `id`, and make it current. Returns its pane id.
    pub fn new_window(&self, id: &str, cwd: &Path) -> Result<String> {
        let target = format!("{id}:");
        let cwd = start_dir(cwd);
        let args = [
            "new-window",
            "-P",
            "-F",
            "#{pane_id}",
            "-t",
            &target,
            "-c",
            &cwd,
        ];
        Ok(self.run(&args)?.trim().to_string())
    }

    /// Split pane `pane`: side by side if `columns`, else top and bottom. The
    /// new shell starts in `cwd` and takes the second half and the focus.
    /// Returns its pane id.
    pub fn split(&self, pane: &str, columns: bool, cwd: &Path) -> Result<String> {
        let cwd = start_dir(cwd);
        let way = if columns { "-h" } else { "-v" };
        let args = [
            "split-window",
            way,
            "-P",
            "-F",
            "#{pane_id}",
            "-t",
            pane,
            "-c",
            &cwd,
        ];
        Ok(self.run(&args)?.trim().to_string())
    }

    /// End a pane; its window goes with its last pane, and the session
    /// with its last window.
    pub fn kill_pane(&self, pane: &str) -> Result<()> {
        self.run(&["kill-pane", "-t", pane]).map(drop)
    }

    /// Rename a window; tmux then stops naming it after its command.
    pub fn rename_window(&self, window: &str, name: &str) -> Result<()> {
        self.run(&["rename-window", "-t", window, name]).map(drop)
    }

    /// Make a window its session's current one and focus pane `pane` in it.
    pub fn select(&self, window: &str, pane: Option<&str>) -> Result<()> {
        let mut args = vec!["select-window", "-t", window];
        if let Some(pane) = pane {
            args.extend([";", "select-pane", "-t", pane]);
        }
        self.run(&args).map(drop)
    }

    /// Focus the pane next to `pane` in direction `flag` (`-L`, `-R`, `-U`, `-D`).
    pub fn select_towards(&self, pane: &str, flag: &str) -> Result<()> {
        self.run(&["select-pane", flag, "-t", pane]).map(drop)
    }

    /// Give `pane` and the panes beside it the same size.
    pub fn spread(&self, pane: &str) -> Result<()> {
        self.run(&["select-layout", "-E", "-t", pane]).map(drop)
    }

    pub fn rename_session(&self, id: &str, name: &str) -> Result<()> {
        self.run(&["rename-session", "-t", id, name]).map(drop)
    }

    /// End a session and everything running in it.
    pub fn kill_session(&self, id: &str) -> Result<()> {
        self.run(&["kill-session", "-t", id]).map(drop)
    }

    /// A format evaluated against a session's active pane, such as `#{pane_id}`.
    pub fn display(&self, id: &str, format: &str) -> Result<String> {
        Ok(self
            .run(&["display-message", "-p", "-t", id, format])?
            .trim()
            .to_string())
    }
}

/// `dir` for `-c`: tmux expands formats there, and `##` is a literal `#`.
fn start_dir(dir: &Path) -> String {
    dir.to_string_lossy().replace('#', "##")
}

/// One tmux session: its stable id (`$N`) and its current name.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Session {
    pub id: String,
    pub name: String,
}

fn parse_sessions(out: &str) -> Vec<Session> {
    let mut rows: Vec<(u64, u64, Session)> = out
        .lines()
        .filter_map(|l| {
            let mut parts = l.splitn(3, ' ');
            let created = parts.next()?.parse().unwrap_or(0);
            let id = parts.next()?.to_string();
            let name = parts.next().unwrap_or_default().to_string();
            let number = id.trim_start_matches('$').parse().unwrap_or(u64::MAX);
            Some((created, number, Session { id, name }))
        })
        .collect();
    rows.sort_by_key(|(created, number, _)| (*created, *number));
    rows.into_iter().map(|(_, _, s)| s).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vars(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    #[test]
    fn clean_env_keeps_only_the_allowlist() {
        let env = clean_env(vars(&[
            ("HOME", "/h"),
            ("SUPACODE_PANE", "1"),
            ("TERM_PROGRAM", "ghostty"),
            ("TERM", "xterm-ghostty"),
            ("TMUX", "/tmp/x,1,0"),
            ("LC_ALL", "C"),
            ("PATH", "/bin"),
            ("XDG_STATE_HOME", "/s"),
            ("PADDOCK_TMUX_SOCKET", "p"),
        ]));
        let keys: Vec<&str> = env.iter().map(|(k, _)| k.as_str()).collect();
        // Hooks in the terminals must find the same state and socket.
        assert_eq!(
            keys,
            [
                "HOME",
                "LC_ALL",
                "PADDOCK_TMUX_SOCKET",
                "PATH",
                "XDG_STATE_HOME",
                "TERM"
            ]
        );
        assert!(env.contains(&("TERM".into(), "xterm-256color".into())));
    }

    #[test]
    fn config_sets_the_agreed_options() {
        let c = config("/bin/zsh");
        for line in [
            "set -s escape-time 0",
            "set -s extended-keys on",
            "set -g status off",
            "set -g prefix None",
            "set -g default-shell '/bin/zsh'",
            "set -g automatic-rename on",
            "set -g allow-rename off",
        ] {
            assert!(c.lines().any(|l| l == line), "missing {line:?}");
        }
    }

    #[test]
    fn sessions_are_ordered_by_creation_then_id_and_keep_spaces_in_names() {
        let out = "200 $10 later\n100 $3 my tab name\n100 $2 first\n";
        let got = parse_sessions(out);
        let ids: Vec<&str> = got.iter().map(|s| s.id.as_str()).collect();
        assert_eq!(ids, ["$2", "$3", "$10"]);
        assert_eq!(got[1].name, "my tab name");
    }

    #[test]
    fn a_start_directory_is_taken_literally() {
        let tmp = tempfile::tempdir().unwrap();
        let server = Server::new(Paths {
            socket: format!("paddock-unit-{}", std::process::id()),
            state_dir: tmp.path().join("state"),
            config_dir: tmp.path().join("config"),
        });
        server.write_config().unwrap();
        // tmux expands formats (`#{…}`, `#(…)`) in a start directory.
        let dir = tmp.path().canonicalize().unwrap().join("x#{session_id}y");
        std::fs::create_dir(&dir).unwrap();
        let started = server.new_session("t", &dir, (80, 24));
        let got = started.and_then(|s| server.display(&s.id, "#{pane_current_path}"));
        let socket = server.run(&["display-message", "-p", "#{socket_path}"]);
        let _ = server.run(&["kill-server"]);
        if let Ok(socket) = socket {
            let _ = std::fs::remove_file(socket.trim());
        }
        assert_eq!(got.unwrap(), dir.to_string_lossy());
    }

    #[test]
    fn tabs_running_a_shell_are_named_after_its_directory_and_others_after_their_command() {
        let tmp = tempfile::tempdir().unwrap();
        let server = Server::new(Paths {
            socket: format!("paddock-unit-names-{}", std::process::id()),
            state_dir: tmp.path().join("state"),
            config_dir: tmp.path().join("config"),
        });
        server.write_config().unwrap();
        let dir = tmp.path().canonicalize().unwrap().join("proj");
        std::fs::create_dir(&dir).unwrap();
        let started = server.new_session("t", &dir, (80, 24));
        // The format, as tmux expands it for each command name.
        let name = |command: &str| {
            let format = AUTO_NAME.replace("#{pane_current_command}", command);
            started
                .as_ref()
                .map_err(|e| anyhow::anyhow!("{e:#}"))
                .and_then(|s| server.display(&s.id, &format))
        };
        let got: Vec<String> = ["zsh", "-zsh", "bash", "sh", "fish", "ssh", "mosh", "vim"]
            .into_iter()
            .map(|c| name(c).unwrap_or_else(|e| format!("{e:#}")))
            .collect();
        let socket = server.run(&["display-message", "-p", "#{socket_path}"]);
        let _ = server.run(&["kill-server"]);
        if let Ok(socket) = socket {
            let _ = std::fs::remove_file(socket.trim());
        }
        assert_eq!(
            got,
            ["proj", "proj", "proj", "proj", "proj", "ssh", "mosh", "vim"]
        );
    }

    #[test]
    fn config_quotes_odd_shell_paths() {
        assert!(config("/opt/it's/sh").contains(r"set -g default-shell '/opt/it'\''s/sh'"));
    }
}
